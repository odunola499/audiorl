from typing import List, Union
import numpy as np
from .data_generation_base import BaseDataGenerator, PreferenceDataPoint, GenerationConfig
from src.audiorl.models.base import PolicyModel, ReferenceModel

class PolicyVsReferenceGenerator(BaseDataGenerator):
    """
    Off-policy preference data generation using policy model for rejected samples
    and a superior offline_reference model for chosen samples.
    
    This strategy generates preference pairs where:
    - Rejected samples: Generated by the policy model (model being trained)
    - Chosen samples: Generated by a superior offline_reference model (e.g., OpenAI API, Gemini)
    
    Useful when you have access to a high-quality offline_reference model and want to
    improve your policy model to match its performance.
    """
    
    def __init__(self, 
                 policy_model: PolicyModel,
                 reference_model: Union[PolicyModel, ReferenceModel],
                 config: GenerationConfig = None):
        super().__init__(policy_model, config)
        self.reference_model = reference_model
    
    def generate_preference_pairs(self, 
                                audio_batch: List[np.ndarray],
                                prompts: List[str] = None) -> List[PreferenceDataPoint]:
        
        rejected_transcriptions = self._transcribe_batch(
            self.policy_model, 
            audio_batch, 
            prompts,
            temperature=self.config.temperature
        )
        
        chosen_transcriptions = self._transcribe_batch(
            self.reference_model,
            audio_batch,
            prompts
        )
        
        preference_pairs = []
        for i, audio in enumerate(audio_batch):
            prompt = prompts[i] if prompts else None
            preference_pairs.append(PreferenceDataPoint(
                audio=audio,
                chosen=chosen_transcriptions[i],
                rejected=rejected_transcriptions[i],
                prompt=prompt
            ))
        
        return preference_pairs